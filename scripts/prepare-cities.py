"""Retain Figma vector paths and coordinates; reuse the working Guangzhou controls.
Original exports are in design-sources/cities. Run from the repository root.
"""
from pathlib import Path
from copy import deepcopy
import json
import xml.etree.ElementTree as E

NS = 'http://www.w3.org/2000/svg'
E.register_namespace('', NS)
def tag(name): return '{%s}%s' % (NS, name)
def by_id(root, name): return next(n for n in root.iter() if n.get('id') == name)
def namespace(root, prefix):
    ids = {n.get('id'): prefix+n.get('id') for n in root.iter() if n.get('id')}
    for n in root.iter():
        for key, value in list(n.attrib.items()):
            if key == 'id': n.set(key, ids[value])
            else:
                for old, new in ids.items():
                    value = value.replace('url(#'+old+')', 'url(#'+new+')')
                    if value == '#'+old: value = '#'+new
                n.set(key, value)

specs = {
 'beijing': ('Beijing','181:5',(489,94,794.8313598632812,819.9999389648438),
  ['Temple of Heaven','Forbidden City','Ludagun','Peking Duck','Lord Rabbit','Swallow Kite']),
 'shanghai': ('Shanghai','189:5',(529.2833251953125,94,714.2647094726562,820.000244140625),
  ['Oriental Pearl Tower','Yuyuan Garden','Eight Treasure Duck','Shengjian Bao','Jinshan Folk Painting','Xuhang Straw Weaving']),
 'dehong': ('Dehong','194:5',(639.7437744140625,94,493.34381103515625,820),
  ['Menghuan Golden Pagoda','Jiele Golden Pagoda','Sapie','Bamboo Rice','Jingpo Brocade','Jingpo Knife']),
 'taiyuan': ('Taiyuan','194:150',(362.2228088378906,94,1048.3857421875,820),
  ['Yongzuo Temple','Chunyang Palace','Youmian Kaolaolao','Knife-cut Noodles','Paper Cutting','Door Gods']),
}
base=E.parse('dist/assets/map/guangzhou.svg').getroot()
base_info=by_id(base,'info')
base_overview=E.parse('dist/assets/map/overview.svg').getroot()
city_data={
 'guangzhou': {'id':'guangzhou','name':'Guangzhou','figmaNode':'1:10306',
  'mapAsset':'./assets/map/guangzhou.svg','minimapAsset':'./assets/map/overview.svg',
  'geography':dict(zip(['x','y','width','height'],[483,123,617.000244,820.00061])),
  'minimapBounds':dict(zip(['x','y','width','height'],[74,803,112,145])),
  'archives':{'Canton Tower':'canton','Guangcai Porcelain':'porcelain'}},
}
for city,(name,node,geo,names) in specs.items():
    root=E.parse('design-sources/cities/'+city+'.svg').getroot()
    root.remove(root[0]) # export preview backing, outside the actual frame
    frame=root[0]
    info=by_id(frame,'info')
    districts=deepcopy(by_id(frame,name+' / districts'))
    frame.remove(by_id(frame,'general button')) # existing fixed navigation is shared
    fixed={info, *[by_id(frame,name+' / '+part) for part in ['blue outline','pink outline','districts']]}
    markers=[n for n in frame if n.tag==tag('g') and n not in fixed]
    assert len(markers)==6, (city,len(markers))
    icons=[]
    for n,label,category in zip(markers,names,['architecture']*2+['food']*2+['craft']*2):
        n.set('data-item',label); n.set('data-category',category)
        icons.append({'name':label,'category':category,'sourceLayer':n.get('id')})
    info.remove(by_id(info,'filter button'));info.remove(by_id(info,'backward'))
    namespace(root,city+'-')
    info.set('data-panel','expanded')
    info.append(deepcopy(by_id(base_info,'filter button')))
    info.append(deepcopy(by_id(base_info,'backward')))
    frame.append(deepcopy(next(n for n in base.iter() if n.get('data-panel')=='collapsed')))
    root.find(tag('defs')).extend(deepcopy(list(base.find(tag('defs')))))
    E.ElementTree(root).write('dist/assets/map/'+city+'.svg',encoding='unicode')
    overview=deepcopy(base_overview)
    mini=by_id(overview,'overview-small Guangzhou map');index=list(overview).index(mini);overview.remove(mini)
    x,y,w,h=geo; scale=min(193/w,145/h)
    mw,mh=w*scale,h*scale; mx,my=130.5-mw/2,874.5-mh/2
    districts.set('transform',f'translate({mx} {my}) scale({scale}) translate({-x} {-y})')
    districts.set('data-minimap-city',city)
    for n in districts.iter():
        if n.get('fill') and n.get('fill')!='none': n.set('fill','#D14596')
        if n.tag==tag('path'):
            n.set('stroke','#812E5E'); n.set('stroke-width',str(.5/scale))
    overview.insert(index,districts)
    namespace(overview,'mini-'+city+'-')
    E.ElementTree(overview).write('dist/assets/map/'+city+'-overview.svg',encoding='unicode')
    city_data[city]={'id':city,'name':name,'figmaNode':node,
      'mapAsset':'./assets/map/'+city+'.svg','minimapAsset':'./assets/map/'+city+'-overview.svg',
      'geography':dict(zip(['x','y','width','height'],geo)),
      'minimapBounds':dict(zip(['x','y','width','height'],[mx,my,mw,mh])), 'icons':icons}
Path('dist/scripts/city-data.js').write_text("// Generated by scripts/prepare-cities.py from the supplied Figma frames.\nimport { iconDisplayName } from './icon-names.js';\nconst citySources = "+json.dumps(city_data,ensure_ascii=False,indent=2)+";\nexport const cities = Object.freeze(Object.fromEntries(Object.entries(citySources).map(([id, city]) => [id, Object.freeze({ ...city, icons: city.icons?.map(icon => ({ ...icon, sourceName: icon.name, name: iconDisplayName(id, icon.name) })) })])));\n")
print('Prepared four city maps and minimaps, preserving all 24 marker drawings.')
